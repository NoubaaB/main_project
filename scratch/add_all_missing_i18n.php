foreach ($locales as $lang) {
    $localFile = dirname(__DIR__) . "/locals/{$lang}.json";
    $appFile = dirname(__DIR__) . "/resources/js/locales/{$lang}/app.json";

    $localData = file_exists($localFile) ? (json_decode(file_get_contents($localFile), true) ?: []) : [];
    $appData = file_exists($appFile) ? (json_decode(file_get_contents($appFile), true) ?: []) : [];

    // Merge: appData + localData so localData (which has 3,422 keys) takes priority
    $merged = array_merge($appData, $localData);

    // Now add new translations
    foreach ($newTranslations as $key => $trans) {
        $merged[$key] = $trans[$lang];
    }

    // Write back both files identically
    $json = json_encode($merged, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n";
    file_put_contents($localFile, $json);
    file_put_contents($appFile, $json);

    echo "Language [{$lang}]: Synchronized. Total keys in both: " . count($merged) . "\n";
}

echo "All 6 translation files successfully updated!\n";
